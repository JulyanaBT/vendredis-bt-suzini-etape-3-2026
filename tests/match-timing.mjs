import {buildTimeline,launchReadiness} from '../assets/js/match-timing.js';

const assert=(v,m)=>{if(!v)throw Error(m);},iso=n=>new Date(n).toISOString(),base=Date.parse('2026-11-06T21:00:00Z'),min=60000;
const ids=Array.from({length:8},(_,i)=>'00000000-0000-4000-8000-'+String(i+1).padStart(12,'0'));
const job=(id,a,b,slot,division='DM')=>({id,a,b,slot,division,court:division,deps:[]});
let ms=[job('A',ids[0],ids[1],0),job('B',ids[2],ids[3],1),job('C',ids[0],ids[2],2),job('D',ids[4],ids[5],0,'DD'),job('E',ids[6],ids[7],1,'DD')];
let r=buildTimeline(ms,{now:base});
assert(r.find(x=>x.id==='B').live===base+35*min,'Men: 30+5');
assert(r.find(x=>x.id==='E').live===base+35*min,'Women: 30+5');
assert(r.find(x=>x.id==='C').live===base+95*min,'Consecutive team: 30 minutes after previous end');
ms=[job('A',ids[0],ids[1],0),job('B',ids[0],ids[2],1)];
ms[0].started_at=iso(base);ms[0].result={validated_at:iso(base+35*min)};
r=buildTimeline(ms,{now:base+35*min});
assert(r[1].live===base+65*min,'Actual match end controls 30-minute rest');
let gate=launchReadiness(ms[1],ms,{now:base+64*min});
assert(!gate.allowed&&gate.until===base+65*min,'Rest blocks early launch');
assert(launchReadiness(ms[1],ms,{now:base+65*min}).allowed,'Launch permitted after rest');
ms[0].result=null;
assert(!launchReadiness(ms[1],ms,{now:base+90*min}).allowed,'Running court blocks launch');
r=buildTimeline(ms,{now:base+90*min});
assert(r[0].end===base+90*min,'Overrunning match remains running until result validation');
ms=[job('A',ids[0],ids[1],0),job('B',ids[2],ids[3],1)];
ms[0].started_at=iso(base-10*min);ms[0].result={validated_at:iso(base+10*min)};
assert(buildTimeline(ms,{now:base})[1].live===base+15*min,'Actual finish + 5-minute gap');
ms[1].forced_at=iso(base+120*min);
assert(buildTimeline(ms,{now:base})[1].live===base+120*min,'Forced hour retained');
console.log('PASS: male/female durations, actual start/end, 30-minute rest, active match exclusion, forced hour');

const cross=[job('X',ids[0],ids[1],0),{...job('Y',ids[0],ids[2],1),court:'DD'}];cross[0].result={validated_at:iso(base+25*min)};assert(!launchReadiness(cross[1],cross,{now:base+40*min}).allowed,'Rest also follows team across courts');assert(buildTimeline(cross,{now:base})[1].live>=base+55*min,'Team rest respected across courts');
const sample=[job('X',ids[0],ids[1],0),job('Y',ids[0],ids[2],1)];
sample[0].result={validated_at:iso(base+25*min)};
let recoveryGate=launchReadiness(sample[1],sample,{now:base+40*min});
assert(!recoveryGate.allowed&&recoveryGate.canConfirm===true,'Short recovery permits explicit confirmation');
sample[0].started_at=iso(base);sample[0].result=null;
recoveryGate=launchReadiness(sample[1],sample,{now:base+40*min});
assert(!recoveryGate.allowed&&!recoveryGate.canConfirm,'Occupied court cannot be bypassed');


const done=job('DONE',ids[0],ids[1],0,'DD');done.started_at=iso(base);done.result={validated_at:iso(base+25*min)};
const principal=job('MAIN',ids[2],ids[3],0);principal.started_at=iso(base+20*min);
const candidate={...job('EXTRA',ids[4],ids[5],1),court:'DD'};
let shared=buildTimeline([done,principal,candidate],{now:base+25*min});
let extra=shared.find(m=>m.id==='EXTRA');
assert(extra.court==='DD'&&extra.live===base+35*min,'Borrowed court: other draw ended, main match overlaps, ten-minute setup');
assert(extra.live<shared.find(m=>m.id==='MAIN').end,'Borrowing must actually parallel the principal match');
let check=launchReadiness(extra,[done,principal,candidate],{now:base+34*min});
assert(!check.allowed&&check.canConfirm&&check.until===base+35*min&&check.reason.includes('Reconfiguration'),'Setup warning retained');
assert(launchReadiness(extra,[done,principal,candidate],{now:base+35*min}).allowed,'Ready borrowed court');
const notFinished={...done,started_at:iso(base+10*min),result:null};
shared=buildTimeline([notFinished,principal,candidate],{now:base+25*min});
assert(shared.find(m=>m.id==='EXTRA').court==='DM','No borrow when other draw forecast ends too late');
assert(!launchReadiness(candidate,[notFinished,principal,candidate],{now:base+100*min}).allowed,'Actual other-draw completion required to launch');
assert(!launchReadiness(candidate,[done,{...principal,result:{validated_at:iso(base+45*min)}},candidate],{now:base+100*min}).allowed,'No borrowed-court launch without a running principal match');
const preserved={...candidate,started_at:iso(base+35*min)};
assert(buildTimeline([done,principal,preserved],{now:base+40*min}).find(m=>m.id==='EXTRA').court==='DD','Never move a match already launched');
console.log('PASS: freed court only, genuine parallel use, ten-minute setup, launch enforcement and preserved active matches');

const consentPair=[job('CONSENT-A',ids[0],ids[1],0,'DD'),job('CONSENT-B',ids[0],ids[2],1,'DD')];
consentPair[1].recovery_agreement={kind:'preapproved',both_teams_agreed:true,previous_match_id:'CONSENT-A',team_ids:[ids[0]]};
let consentTimeline=buildTimeline(consentPair,{now:base});
assert(consentTimeline[1].live===consentTimeline[0].end+5*min,'Preapproved recovery retains five-minute gap');
consentPair[0].started_at=iso(base);consentPair[0].result={validated_at:iso(base+30*min)};
assert(!launchReadiness(consentPair[1],consentPair,{now:base+30*min}).allowed,'Five-minute gap still required after actual end');
assert(launchReadiness(consentPair[1],consentPair,{now:base+35*min}).allowed,'Recorded consent allows launch after five-minute gap');
const unrelated={...consentPair[1],recovery_agreement:{...consentPair[1].recovery_agreement,previous_match_id:'OTHER'}};
assert(launchReadiness(unrelated,consentPair,{now:base+30*min}).canConfirm,'Consent cannot apply to another match');
consentPair[0].result=null;
assert(!launchReadiness(consentPair[1],consentPair,{now:base+30*min}).allowed,'Consent cannot bypass an active match');
console.log('PASS: scoped preapproved recovery, five-minute gap and active match safety');
